CREATE TABLE public.events (
    id bigint NOT NULL,
    event_id integer,
    extra character varying(255),
    incident_id bigint,
    level_display_name character varying(255),
    machine_name character varying(255),
    message text,
    processed boolean,
    record_id bigint,
    time_created timestamp(6) without time zone
);

CREATE SEQUENCE public.events_seq
    START WITH 1
    INCREMENT BY 50
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

CREATE TABLE public.incidents (
    id bigint NOT NULL,
    affected_user character varying(255),
    closed_at timestamp(6) without time zone,
    closed_by character varying(255),
    context text,
    created_at timestamp(6) without time zone NOT NULL,
    deduplication_key character varying(255),
    event_count integer,
    first_event_time timestamp(6) without time zone,
    last_event_time timestamp(6) without time zone,
    machine_name character varying(255),
    meta boolean,
    name character varying(255) NOT NULL,
    recommendation text,
    severity character varying(20) NOT NULL,
    signal_id character varying(20) NOT NULL,
    status character varying(20) NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT incidents_severity_check CHECK (((severity)::text = ANY ((ARRAY['LOW'::character varying, 'MEDIUM'::character varying, 'HIGH'::character varying, 'CRITICAL'::character varying])::text[]))),
    CONSTRAINT incidents_status_check CHECK (((status)::text = ANY ((ARRAY['OPEN'::character varying, 'IN_PROGRESS'::character varying, 'RESOLVED'::character varying, 'FALSE_POSITIVE'::character varying, 'CLOSED'::character varying])::text[])))
);

ALTER TABLE public.incidents ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.incidents_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.events
    ADD CONSTRAINT events_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.incidents
    ADD CONSTRAINT idx_incident_hash UNIQUE (deduplication_key);

ALTER TABLE ONLY public.incidents
    ADD CONSTRAINT incidents_pkey PRIMARY KEY (id);

